def add_stops():
    p = ROOT / "data" / "diseases.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    for rid, seg_name, stop in STOPS:
        region = next(r for r in d["regions"] if r["id"] == rid)
        if any(st["slug"] == stop["slug"] for s in region["segments"] for st in s["stops"]):
            continue
        seg = next((s for s in region["segments"] if s["name"] == seg_name), None)
        if not seg:
            seg = {"name": seg_name, "stops": []}
            after = NEW_SEGMENT_AFTER[seg_name]
            i = next(i for i, s in enumerate(region["segments"]) if s["name"] == after)
            region["segments"].insert(i + 1, seg)
        seg["stops"].append({**stop, "published": DATE})
    p.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    p = ROOT / "data" / "symptoms.json"
    s = json.loads(p.read_text(encoding="utf-8"))
    for it in s["items"]:
        for slug in SYMPTOM_ADD.get(it["q"], []):
            if slug not in it["slugs"]:
                it["slugs"].append(slug)
    for it in SYMPTOM_NEW:
        if not any(x["q"] == it["q"] for x in s["items"]):
            s["items"].append(it)
    p.write_text(json.dumps(s, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("stops added:", [st["slug"] for _, _, st in STOPS])


